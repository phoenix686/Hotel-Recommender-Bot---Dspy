def extract_question(text):
    try:
        if 'Question:' in text:
            # Split at 'Question:'
            part_after_question = text.split('Question:')[1]
            # Further split at 'True.' or other possible markers
            question = part_after_question.split('True.')[0].strip()
            return question

        elif 'Answer:' in text:
            part_after_answer = text.split('Answer:')[1]
            # Further split at 'Exercise' if it exists
            question = part_after_answer.split('Exercise')[0].strip()
            return question

        elif 'The answer should be' in text:
            part_after_answer = text.split('The answer should be')[1]
            # Split before 'Exercise' if it exists
            question = part_after_answer.split('Exercise')[0].strip().strip('"')
            return question

        elif '#' in text:
            return text.split('asking')[1].split('  ```')[0]

        elif 'Title' in text:
            return text.split('Title')[0].strip().strip('"')
        elif '(1)' in text:
            return text.split('(1)')[0].strip()

    except IndexError:
        # Handle cases where the expected text pattern is not found
        return text

    # Default case if neither 'Question:' nor 'Answer:' is found
    return text.strip('\'')

data['question'] = data['question'].apply(extract_question)
data.to_csv('qa_pair_dataset.csv')

