tokenizer = AutoTokenizer.from_pretrained("microsoft/phi-1_5")
model = AutoModelForCausalLM.from_pretrained("microsoft/phi-1_5")

max_input_length=700

#system_prompt = "You are a helpful assistant. Given the context, generate a relevant question."
tokenizer.pad_token = tokenizer.eos_token
def generate_question(prompt):
    # prompt = f"{system_prompt} Context: {context}"
    inputs = tokenizer(prompt, return_tensors="pt", truncation=True, max_length=max_input_length, padding=True)
    outputs = model.generate(
        inputs.input_ids,
        max_new_tokens=50,
        pad_token_id=tokenizer.eos_token_id,
        attention_mask=inputs.attention_mask,

    )
    question = tokenizer.decode(outputs[0], skip_special_tokens=True).replace('\n', ' ').strip()
    return question

# Generate different types of questions for each row
def create_questions(row):
    questions = []

    # Generate a question about the review
    prompt_review = f"Create a question asking about the review of {row['hotel']} in {row['city']}"
    question_review = generate_question(prompt_review)
    questions.append({"question": question_review, "answer": row['review']})

    # Generate a question about the city
    prompt_city = f"Create a question asking which city {row['hotel']} is located in."
    question_city = generate_question(prompt_city)
    questions.append({"question": question_city, "answer": row['city']})

    # Generate a question about the hotel
    prompt_hotel = f"Review: '{row['review']}'.Given this review, generate an apt question suiting {row['hotel']}? "
    question_hotel = generate_question(prompt_hotel)
    questions.append({"question": question_hotel, "answer": row['hotel']})

    return questions

# Apply the function to each row and create a list of examples
all_examples = []
for _, row in tqdm(df.iterrows(), total=df.shape[0]):
    all_examples.extend(create_questions(row))

# all_examples
